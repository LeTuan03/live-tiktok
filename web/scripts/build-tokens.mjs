#!/usr/bin/env node
// Reads web/lib/branding/colors.json (the canonical brand token source) and
// emits web/styles/tokens.css. Tailwind reads the same JSON via
// tailwind.config.ts so utility classes and CSS variables stay in lock-step.
//
// To change a brand color, edit lib/branding/colors.json, rerun this script
// (`npm run build:tokens`), and commit the regenerated tokens.css. Do not
// hand-copy hex values elsewhere in the web codebase.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(__dirname, "..");
const tokensPath = resolve(webRoot, "lib/branding/colors.json");
const outPath = resolve(webRoot, "styles", "tokens.css");

const tokens = JSON.parse(readFileSync(tokensPath, "utf8"));
const c = tokens.color;

const cssVar = (name, value) => `  --${name}: ${value};`;

const brandVars = Object.entries(c.brand).map(([k, v]) => cssVar(`brand-${k}`, v.value));
const neutralVars = Object.entries(c.neutral).map(([k, v]) => cssVar(`neutral-${k}`, v.value));
const semanticVars = Object.entries(c.semantic).map(([k, v]) => cssVar(`semantic-${k}`, v.value));
const adVars = Object.entries(c.ad).map(([k, v]) =>
  cssVar(`ad-${k.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase())}`, v.value),
);

const surfaceVars = (mode) =>
  Object.entries(c.surface[mode]).map(([k, v]) =>
    cssVar(`surface-${k.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase())}`, v.value),
  );

const gradient = c.gradient.primary.value;
const gradientCss = `linear-gradient(${gradient.angle}, ${gradient.stops
  .map((s) => `${s.color} ${Math.round(s.position * 100)}%`)
  .join(", ")})`;
const warmAccent = c.gradient.warmAccent.value;
const warmAccentCss = `linear-gradient(${warmAccent.angle}, ${warmAccent.stops
  .map((s) => `${s.color} ${Math.round(s.position * 100)}%`)
  .join(", ")})`;

const out = `/* AUTO-GENERATED by web/scripts/build-tokens.mjs. Do not edit by hand. */
/* Source: web/lib/branding/colors.json */

:root {
${brandVars.join("\n")}
${neutralVars.join("\n")}
${semanticVars.join("\n")}
${adVars.join("\n")}

  /* Default surface = light (partner / advertiser portal). */
${surfaceVars("light").join("\n")}

  --brand-gradient-primary: ${gradientCss};
  --brand-gradient-warm-accent: ${warmAccentCss};
}

/* Consumer chrome: opt-in dark surface via .theme-consumer on <body>. */
.theme-consumer {
${surfaceVars("dark").join("\n")}
  color-scheme: dark;
}

/* Partner chrome explicitly opts back into light, in case a parent has flipped it. */
.theme-partner {
${surfaceVars("light").join("\n")}
  color-scheme: light;
}
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`[build-tokens] wrote ${outPath}`);
