// Shared, non-removable AI-disclosure chip.
//
// Mounted on every persona-related surface: feed cards, the ask-avatar
// surface (`PersonaSurface`), the persona profile page, and the live-show
// status overlay. The chip has no dismiss control, no programmatic close,
// and no `aria-hidden`, so a viewer can never lose sight of the disclosure.
//
// The contract is intentionally narrow (variant + optional `className` for
// positioning) so callers can drop it in without restructuring their layout.

import type { CSSProperties } from "react";

export type AIDisclosureVariant = "avatar" | "host" | "creator";

interface AIDisclosureChipProps {
  /**
   * Surface label. The wording is fixed, but the surface context shifts:
   * feed cards say "AI Creator", live-show chrome says "AI host", profile
   * and ask-avatar say "AI avatar". Default is "avatar", which matches the
   * persona profile page.
   */
  variant?: AIDisclosureVariant;
  /**
   * Optional positioning / spacing classes layered on top of the base
   * pill styling. The chip is `pointer-events-none` by default so it
   * never swallows taps from the surface beneath it.
   */
  className?: string;
  /** Optional inline style for callers that need precise placement. */
  style?: CSSProperties;
}

const COPY: Record<AIDisclosureVariant, { label: string; ariaLabel: string; title: string }> = {
  avatar: {
    label: "AI avatar",
    ariaLabel: "You are talking to an AI avatar",
    title: "The avatar in this conversation is generated by AI.",
  },
  host: {
    label: "AI host",
    ariaLabel: "This show is hosted by an AI avatar",
    title: "The host of this show is an AI avatar.",
  },
  creator: {
    label: "AI Creator",
    ariaLabel: "This persona is an AI creator",
    title: "This persona is generated by AI.",
  },
};

const BASE_CLASSES =
  "pointer-events-none inline-flex items-center gap-1 rounded-full bg-black/60 px-2 py-1 text-[11px] font-semibold uppercase tracking-wide text-white shadow ring-1 ring-white/15 backdrop-blur";

/**
 * Renders the permanent AI-disclosure pill. The element is a `<span>`
 * with `role="note"` so screen readers announce it as a non-interactive
 * advisory rather than a button or status region. There is intentionally
 * no close affordance — the component does not accept `onDismiss`, has
 * no `hidden` prop, and exposes no imperative handle.
 */
export function AIDisclosureChip({ variant = "avatar", className, style }: AIDisclosureChipProps) {
  const copy = COPY[variant];
  const merged = className ? `${BASE_CLASSES} ${className}` : BASE_CLASSES;
  return (
    <span
      role="note"
      aria-label={copy.ariaLabel}
      title={copy.title}
      data-testid="ai-disclosure"
      className={merged}
      style={style}
    >
      <span aria-hidden>●</span>
      {copy.label}
    </span>
  );
}
